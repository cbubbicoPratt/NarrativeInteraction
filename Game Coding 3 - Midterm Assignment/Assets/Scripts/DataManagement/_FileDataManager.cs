using UnityEngine;
using System;
using System.IO;

public class _FileDataManager
{
    private string dataDirectoryPath = "";
    private string dataFileName = "";

    //constructor of the class, but takes 2 arguments
    //like other constructors, allows us to create instances of class w/ data preloaded
    public _FileDataManager(string dataDirPath, string dataFileName)
    {
        this.dataDirectoryPath = dataDirPath;
        this.dataFileName = dataFileName;
    }

    public _GameData LoadFile()
    {
        _GameData loadedData = null;
        
        return loadedData;
    }

    public void SaveFile(_GameData data)
    {
        //this string is the directory path on our local machine
        //being generated by "dataDirectoryPath" and "dataFileName" variables
        //like writing "Desktop/Folder/Data" + "fileName"
        string fullPathToFile = Path.Combine(dataDirectoryPath, dataFileName);

        //try/catch are a type of logic that allows you to create non-conditional breaks in your code
        //below code attempted to be executed, but if error breaks logic of "try"
        //catch "reports" the exception error 'e' in a Debug.LogError
        try
        {
            //creates file + directory at the location we specified in the string "fullPathToFile"
            Directory.CreateDirectory(Path.GetDirectoryName(fullPathToFile));

            //dataToStore is serialized data from our GameData argument, "prettyPrint" organized as readable string
            //this will be written into our file on our local machine
            string dataToStore = JsonUtility.ToJson(data, true);

            //'using' is a type of logic where condition checks to make sure whatever System.IO class that is being opened
            //is then safely closed if any errors occur in the process within that logic block
            //this will prevent data leaks in your software!! 
            using (FileStream stream = new FileStream(fullPathToFile, FileMode.Create))
            {
                using (StreamWriter writer = new StreamWriter(stream))
                {
                    writer.Write(dataToStore);
                }
            }
        }
        catch(Exception e)
        {
            Debug.LogError("Path does not exist: "  + fullPathToFile + "\n" + e);
        }
    }
}
